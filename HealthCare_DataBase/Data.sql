-- 1. Drop existing tables safely in reverse foreign key order
IF OBJECT_ID('dbo.Prescriptions', 'U') IS NOT NULL DROP TABLE dbo.Prescriptions;
IF OBJECT_ID('dbo.Appointments', 'U') IS NOT NULL DROP TABLE dbo.Appointments;
IF OBJECT_ID('dbo.Physicians', 'U') IS NOT NULL DROP TABLE dbo.Physicians;
IF OBJECT_ID('dbo.Patients', 'U') IS NOT NULL DROP TABLE dbo.Patients;
IF OBJECT_ID('dbo.Facilities', 'U') IS NOT NULL DROP TABLE dbo.Facilities;
GO

-- 2. Recreate Tables
CREATE TABLE Facilities (
    FacilityID INT PRIMARY KEY IDENTITY(1,1),
    FacilityName VARCHAR(100) NOT NULL,
    City VARCHAR(50) NOT NULL,
    State VARCHAR(2) NOT NULL
);

CREATE TABLE Patients (
    PatientID INT PRIMARY KEY IDENTITY(1,1),
    FirstName VARCHAR(50) NOT NULL,
    LastName VARCHAR(50) NOT NULL,
    DOB DATE NOT NULL,
    Gender CHAR(1) CHECK (Gender IN ('M', 'F')),
    City VARCHAR(50) NOT NULL,
    RegistrationDate DATE NOT NULL
);

CREATE TABLE Physicians (
    PhysicianID INT PRIMARY KEY IDENTITY(1,1),
    FirstName VARCHAR(50) NOT NULL,
    LastName VARCHAR(50) NOT NULL,
    Specialty VARCHAR(50) NOT NULL,
    FacilityID INT FOREIGN KEY REFERENCES Facilities(FacilityID)
);

CREATE TABLE Appointments (
    AppointmentID INT PRIMARY KEY IDENTITY(1,1),
    PatientID INT FOREIGN KEY REFERENCES Patients(PatientID),
    PhysicianID INT FOREIGN KEY REFERENCES Physicians(PhysicianID),
    AppointmentDate DATETIME NOT NULL,
    Diagnosis VARCHAR(100) NULL,
    BillingAmount DECIMAL(10,2) NOT NULL,
    Status VARCHAR(20) DEFAULT 'Completed'
);

CREATE TABLE Prescriptions (
    PrescriptionID INT PRIMARY KEY IDENTITY(1,1),
    AppointmentID INT FOREIGN KEY REFERENCES Appointments(AppointmentID),
    MedicationName VARCHAR(100) NOT NULL,
    Dosage VARCHAR(50) NOT NULL,
    Cost DECIMAL(10,2) NOT NULL,
    PrescriptionDate DATE NOT NULL
);
